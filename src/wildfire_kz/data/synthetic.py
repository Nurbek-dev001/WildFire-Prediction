"""Offline SYNTHETIC data generator.

Produces a small, internally consistent multisource dataset in the *same raw formats* the
real-data readers consume, so that every pipeline stage and every test runs without network
access or real data:

* FIRMS-like VIIRS archive CSVs (with n/h/l confidence, ``type`` field, duplicates,
  persistent industrial hotspots and missed overpasses),
* ERA5-Land-like hourly monthly NetCDF files following the ERA5-Land accumulation convention
  for ``tp`` (accumulated since 00 UTC; the 00 UTC step holds the previous day's total),
* MOD13A2-like 16-day NDVI/EVI/SummaryQA GeoTIFFs, MCD12Q1-like annual IGBP land cover,
  SRTM-like DEM tiles, WorldPop-like population-count rasters,
* settlement points and dated road-network snapshots (GeoJSON).

Fire occurrence is simulated from *same-day* synthetic weather, fuel state, land cover and
human access, so models restricted to information up to t-1 have realistic (imperfect) skill.

Nothing produced here is real data. Every file carries a SYNTHETIC marker and a
``SYNTHETIC_DATA.txt`` file is written at the raw-data root; the ingest stage propagates this
flag into the manifest and every report.
"""

from __future__ import annotations

import datetime as dt
from dataclasses import dataclass
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
import xarray as xr
from rasterio.transform import from_origin
from scipy.ndimage import gaussian_filter
from shapely.geometry import LineString, Point, Polygon

from wildfire_kz.config.schema import Config
from wildfire_kz.data.rasterio_utils import write_geotiff
from wildfire_kz.utils.runtime import derive_seed, get_logger, write_json

log = get_logger("synthetic")

SYNTHETIC_MARKER = "SYNTHETIC_DATA.txt"
_TAGS = {"SYNTHETIC": "true", "DESCRIPTION": "Synthetic test data generated by wildfire_kz; "
         "NOT a real observation."}

# IGBP codes used by the synthetic land-cover model
_FOREST, _SHRUB, _SAVANNA, _GRASS, _WET, _CROP, _URBAN, _MOSAIC, _BARREN, _WATER = (
    4, 7, 9, 10, 11, 12, 13, 14, 16, 17)


@dataclass
class _LonLatGrid:
    west: float
    north: float
    res: float
    nx: int
    ny: int

    @property
    def lons(self) -> np.ndarray:
        return self.west + self.res * (np.arange(self.nx) + 0.5)

    @property
    def lats(self) -> np.ndarray:
        return self.north - self.res * (np.arange(self.ny) + 0.5)

    @property
    def transform(self):  # type: ignore[no-untyped-def]
        return from_origin(self.west, self.north, self.res, self.res)


def _grid_for(bbox: tuple[float, float, float, float], res: float, margin: float = 0.0
              ) -> _LonLatGrid:
    w, s, e, n = bbox
    w, s, e, n = w - margin, s - margin, e + margin, n + margin
    nx = int(np.ceil((e - w) / res))
    ny = int(np.ceil((n - s) / res))
    return _LonLatGrid(west=w, north=n, res=res, nx=nx, ny=ny)


def _smooth(rng: np.random.Generator, shape: tuple[int, int], sigma: float) -> np.ndarray:
    f = gaussian_filter(rng.standard_normal(shape), sigma=sigma, mode="reflect")
    return (f - f.mean()) / (f.std() + 1e-12)


def _sample(field: np.ndarray, g: _LonLatGrid, lon: np.ndarray, lat: np.ndarray) -> np.ndarray:
    col = np.clip(((lon - g.west) / g.res).astype(int), 0, g.nx - 1)
    row = np.clip(((g.north - lat) / g.res).astype(int), 0, g.ny - 1)
    return field[row, col]


def _bilinear_matrix(src: _LonLatGrid, lon: np.ndarray, lat: np.ndarray) -> np.ndarray:
    """Dense (n_points, ny*nx) bilinear interpolation weights from a lon/lat grid."""
    fx = np.clip((lon - src.lons[0]) / src.res, 0, src.nx - 1 - 1e-9)
    fy = np.clip((src.lats[0] - lat) / src.res, 0, src.ny - 1 - 1e-9)
    x0, y0 = np.floor(fx).astype(int), np.floor(fy).astype(int)
    x1, y1 = np.minimum(x0 + 1, src.nx - 1), np.minimum(y0 + 1, src.ny - 1)
    wx, wy = fx - x0, fy - y0
    w = np.zeros((lon.size, src.ny * src.nx))
    idx = np.arange(lon.size)
    for yy, xx, ww in ((y0, x0, (1 - wx) * (1 - wy)), (y0, x1, wx * (1 - wy)),
                       (y1, x0, (1 - wx) * wy), (y1, x1, wx * wy)):
        np.add.at(w, (idx, yy * src.nx + xx), ww)
    return w


class SyntheticGenerator:
    """Generate a complete synthetic raw-data tree under ``cfg.project.raw_dir``."""

    def __init__(self, cfg: Config) -> None:
        self.cfg = cfg
        self.sc = cfg.synthetic
        self.raw = cfg.project.raw_dir
        self.seed = cfg.project.seed
        self.d0 = cfg.study.start - dt.timedelta(days=cfg.study.lookback_days)
        self.d1 = cfg.study.end + dt.timedelta(days=1)  # ERA5 needs 00 UTC of end+1
        self.days = pd.date_range(self.d0, self.d1, freq="D")
        self.bbox = self.sc.bbox_lonlat
        self.base = _grid_for(self.bbox, self.sc.landcover_resolution_deg, margin=0.05)

    def _rng(self, *tags: object) -> np.random.Generator:
        return np.random.default_rng(derive_seed(self.seed, "synthetic", *tags))

    # ------------------------------------------------------------------ orchestration
    def generate(self) -> Path:
        self.raw.mkdir(parents=True, exist_ok=True)
        log.info("generating SYNTHETIC data in %s for %s..%s", self.raw, self.d0, self.d1)
        self._boundary()
        self._static_fields()
        self._settlements_and_roads()
        self._landcover()
        self._dem()
        self._worldpop()
        weather = self._era5()
        self._modis(weather)
        self._fires(weather)
        (self.raw / SYNTHETIC_MARKER).write_text(
            "All files in this directory tree were generated by wildfire_kz.data.synthetic.\n"
            "They are SYNTHETIC and must never be reported as real observations.\n"
            f"seed={self.seed}\n"
        )
        write_json(self.raw / "synthetic_generator.json", {
            "seed": self.seed, "bbox": self.bbox, "start": self.d0, "end": self.d1,
            "config": self.sc.model_dump(mode="json")})
        return self.raw

    # ------------------------------------------------------------------ boundary
    def _boundary(self) -> None:
        rng = self._rng("boundary")
        w, s, e, n = self.bbox
        cx, cy = (w + e) / 2, (s + n) / 2
        rx, ry = (e - w) / 2 * 0.92, (n - s) / 2 * 0.92
        ang = np.linspace(0, 2 * np.pi, 48, endpoint=False)
        wobble = 1 + 0.06 * np.sin(3 * ang + rng.uniform(0, 6)) + 0.03 * rng.standard_normal(48)
        # superellipse keeps the polygon blocky enough for block CV
        xs = cx + rx * np.sign(np.cos(ang)) * np.abs(np.cos(ang)) ** 0.5 * wobble
        ys = cy + ry * np.sign(np.sin(ang)) * np.abs(np.sin(ang)) ** 0.5 * wobble
        xs = np.clip(xs, w, e)
        ys = np.clip(ys, s, n)
        poly = Polygon(zip(xs, ys, strict=True)).buffer(0)
        gdf = gpd.GeoDataFrame({"name": ["SYNTHETIC boundary (not the real Kazakhstan border)"],
                                "synthetic": [True]}, geometry=[poly], crs="EPSG:4326")
        path = self.cfg.raw(self.cfg.sources.boundary.path)
        path.parent.mkdir(parents=True, exist_ok=True)
        gdf.to_file(path, driver="GeoJSON")

    # ------------------------------------------------------------------ static fields
    def _static_fields(self) -> None:
        rng = self._rng("static")
        g = self.base
        shape = (g.ny, g.nx)
        lat = g.lats[:, None] * np.ones((1, g.nx))
        ridge = _smooth(rng, shape, sigma=max(shape) / 6)
        rough = _smooth(rng, shape, sigma=max(shape) / 40)
        self.elev = (450 + 380 * np.clip(ridge, -0.5, 3) + 60 * rough).astype(np.float32)
        moist = _smooth(rng, shape, sigma=max(shape) / 8) + 0.6 * (lat - lat.mean())
        self.moist = moist
        self.crop_field = _smooth(rng, shape, sigma=max(shape) / 12) + 0.5 * moist
        self.patch = _smooth(rng, shape, sigma=max(shape) / 60)

    def _base_landcover(self) -> np.ndarray:
        lc = np.full(self.elev.shape, _GRASS, dtype=np.uint8)
        lc[self.moist < -0.9] = _SHRUB
        lc[self.crop_field > 0.6] = _CROP
        lc[(self.crop_field > 0.35) & (self.crop_field <= 0.6)] = _MOSAIC
        lc[self.elev > np.quantile(self.elev, 0.9)] = _FOREST
        lc[(self.elev > np.quantile(self.elev, 0.84)) & (lc == _GRASS)] = _SAVANNA
        lc[self.patch > 2.3] = _WATER
        lc[(self.patch < -2.2)] = _BARREN
        lc[(self.moist > 1.8) & (self.patch > 1.2)] = _WET
        return lc

    # ------------------------------------------------------------------ human
    def _settlements_and_roads(self) -> None:
        rng = self._rng("human")
        g = self.base
        n = self.sc.n_settlements
        w, s, e, nn = self.bbox
        lon = rng.uniform(w, e, n)
        lat = rng.uniform(s, nn, n)
        size = np.exp(rng.normal(8.0, 1.2, n))  # inhabitants
        self.settlements = pd.DataFrame({"lon": lon, "lat": lat, "population": size})
        settle_cfg = self.cfg.sources.settlements
        for snap in settle_cfg.snapshots:
            gdf = gpd.GeoDataFrame(
                {"name": [f"SYN-{i}" for i in range(n)], "population": size.round(),
                 "synthetic": True}, geometry=gpd.points_from_xy(lon, lat), crs="EPSG:4326")
            p = self.cfg.raw(snap.path)
            p.parent.mkdir(parents=True, exist_ok=True)
            gdf.to_file(p, driver="GeoJSON")
        # road network: nearest-neighbour links, progressively built over the snapshots
        order = np.argsort(-size)
        segments: list[LineString] = []
        build_rank: list[int] = []
        for rank, i in enumerate(order[1:], start=1):
            prev = order[:rank]
            d = np.hypot(lon[prev] - lon[i], lat[prev] - lat[i])
            j = prev[np.argmin(d)]
            mid = ((lon[i] + lon[j]) / 2 + rng.normal(0, 0.05), (lat[i] + lat[j]) / 2
                   + rng.normal(0, 0.05))
            segments.append(LineString([(lon[j], lat[j]), mid, (lon[i], lat[i])]))
            build_rank.append(rank)
        rank_arr = np.asarray(build_rank)
        snaps = sorted(self.cfg.sources.roads.snapshots, key=lambda s: s.snapshot_date)
        self.road_lines_by_snapshot: list[tuple[dt.date, list[LineString]]] = []
        for k, snap in enumerate(snaps, start=1):
            share = 0.6 + 0.4 * k / max(len(snaps), 1)
            keep = rank_arr <= int(np.ceil(share * len(segments)))
            lines = [seg for seg, kk in zip(segments, keep, strict=True) if kk]
            self.road_lines_by_snapshot.append((snap.snapshot_date, lines))
            gdf = gpd.GeoDataFrame({"highway": "secondary", "synthetic": True},
                                   index=range(len(lines)), geometry=lines, crs="EPSG:4326")
            p = self.cfg.raw(snap.path)
            p.parent.mkdir(parents=True, exist_ok=True)
            gdf.to_file(p, driver="GeoJSON")
        self.all_roads = segments
        # population density surface (persons/km²) on the base grid
        lons, lats = np.meshgrid(g.lons, g.lats)
        dens = np.zeros_like(lons)
        for x, y, pop in zip(lon, lat, size, strict=True):
            r2 = ((lons - x) * np.cos(np.deg2rad(y))) ** 2 + (lats - y) ** 2
            dens += pop / (2 * np.pi * 0.05**2 * 111**2) * np.exp(-r2 / (2 * 0.05**2))
        self.pop_density = dens + 0.5  # rural background

    # ------------------------------------------------------------------ land cover
    def _landcover(self) -> None:
        src = self.cfg.sources.mcd12q1
        base = self._base_landcover()
        g = self.base
        lons, lats = np.meshgrid(g.lons, g.lats)
        for x, y, pop in self.settlements.itertuples(index=False):
            r = 0.004 * np.sqrt(pop / 1000)
            base[((lons - x) ** 2 + (lats - y) ** 2) < r**2] = _URBAN
        # persistent industrial heat sources sit on small non-vegetated (barren) patches
        # well inside the domain
        rng_i = self._rng("industrial_sites")
        w, s_, e, n = self.bbox
        self.industrial_sites = []
        for _ in range(self.sc.n_industrial_sites):
            lon_i = rng_i.uniform(w + 0.3 * (e - w), e - 0.3 * (e - w))
            lat_i = rng_i.uniform(s_ + 0.3 * (n - s_), n - 0.3 * (n - s_))
            near = (np.abs(lons - lon_i) < 0.02) & (np.abs(lats - lat_i) < 0.015)
            base[near] = _BARREN
            self.industrial_sites.append((float(lon_i), float(lat_i)))
        self.lc_base = base
        self.lc_by_year: dict[int, np.ndarray] = {}
        for year in range(self.d0.year - 1, self.cfg.study.end.year + 1):
            rng = self._rng("lc", year)
            lc = base.copy()
            flip = (rng.random(lc.shape) < 0.01) & np.isin(lc, [_GRASS, _MOSAIC, _CROP])
            lc[flip] = rng.choice([_GRASS, _MOSAIC, _CROP], flip.sum())
            self.lc_by_year[year] = lc
            write_geotiff(self.cfg.raw(src.path) / f"MCD12Q1_061_{year}.tif", lc, g.transform,
                          "EPSG:4326", nodata=255, tags={**_TAGS, "LC_TYPE": "IGBP LC_Type1"},
                          band_descriptions=["LC_Type1"])

    # ------------------------------------------------------------------ DEM
    def _dem(self) -> None:
        src = self.cfg.sources.srtm
        g = self.base
        tx, ty = self.sc.dem_tiles
        xs = np.array_split(np.arange(g.nx), tx)
        ys = np.array_split(np.arange(g.ny), ty)
        dem = np.round(self.elev).astype(np.int16)
        for j, rows in enumerate(ys):
            for i, cols in enumerate(xs):
                west = g.west + cols[0] * g.res
                north = g.north - rows[0] * g.res
                tile = dem[rows[0]:rows[-1] + 1, cols[0]:cols[-1] + 1]
                write_geotiff(self.cfg.raw(src.path) / f"SRTM_tile_{j}_{i}.tif", tile,
                              from_origin(west, north, g.res, g.res), "EPSG:4326",
                              nodata=int(src.nodata), tags=_TAGS, band_descriptions=["elevation"])

    # ------------------------------------------------------------------ WorldPop
    def _worldpop(self) -> None:
        from wildfire_kz.data.rasterio_utils import geographic_pixel_area_km2

        src = self.cfg.sources.worldpop
        g = _grid_for(self.bbox, self.sc.worldpop_resolution_deg, margin=0.05)
        # resample density to worldpop grid by sampling
        lons, lats = np.meshgrid(g.lons, g.lats)
        dens = _sample(self.pop_density, self.base, lons.ravel(), lats.ravel()).reshape(lons.shape)
        area = geographic_pixel_area_km2(g.lats, g.res)[:, None]
        for year in range(self.d0.year - 1, self.cfg.study.end.year + 1):
            growth = 1.012 ** (year - 2015)
            counts = (dens * area * growth).astype(np.float32)
            write_geotiff(self.cfg.raw(src.path) / f"kaz_ppp_{year}.tif", counts, g.transform,
                          "EPSG:4326", nodata=-99999.0, tags={**_TAGS, "UNITS": "persons/pixel"})

    # ------------------------------------------------------------------ ERA5-Land
    def _era5(self) -> dict[str, np.ndarray]:
        """Simulate daily weather on the ERA5 grid, write hourly monthly NetCDF files.

        Returns daily fields (days, ny, nx) used to drive vegetation and fire simulation.
        """
        src = self.cfg.sources.era5_land
        g = _grid_for(self.bbox, self.sc.era5_resolution_deg, margin=self.sc.era5_resolution_deg)
        self.era_grid = g
        rng = self._rng("era5")
        nd = len(self.days)
        doy = self.days.dayofyear.to_numpy()
        lat2d = g.lats[:, None] * np.ones((1, g.nx))
        xnorm = np.linspace(-1, 1, g.nx)[None, :] * np.ones((g.ny, 1))
        ynorm = np.linspace(-1, 1, g.ny)[:, None] * np.ones((1, g.nx))
        elev = _sample(self.elev, self.base, (np.meshgrid(g.lons, g.lats)[0]).ravel(),
                       (np.meshgrid(g.lons, g.lats)[1]).ravel()).reshape(g.ny, g.nx)

        def ar1(n: int, phi: float, sd: float, k: int = 3) -> np.ndarray:
            e = rng.normal(0, sd * np.sqrt(1 - phi**2), (n, k))
            out = np.zeros((n, k))
            for t in range(1, n):
                out[t] = phi * out[t - 1] + e[t]
            return out

        t_an = ar1(nd, 0.8, 3.5)
        dry = ar1(nd, 0.85, 1.0, 1)[:, 0]
        wind_an = ar1(nd, 0.6, 1.2)
        season = np.sin(2 * np.pi * (doy - 105) / 365.25)
        tclim = (4.0 + 18.5 * season)[:, None, None] - 0.7 * (lat2d - 49) - 0.0065 * (elev - 400)
        tmean = tclim + t_an[:, [0]][:, :, None] + t_an[:, [1]][:, :, None] * xnorm \
            + t_an[:, [2]][:, :, None] * ynorm * 0.5
        dtr = 11.0 + 2.5 * dry[:, None, None] + 0 * xnorm
        # precipitation occurrence & amount (mm/day)
        wet_prob = 0.22 + 0.08 * np.sin(2 * np.pi * (doy - 120) / 365.25) - 0.08 * dry
        noise = rng.standard_normal((nd, g.ny, g.nx)) * 0.6 + rng.standard_normal((nd, 1, 1))
        from scipy.stats import norm

        occ = noise < norm.ppf(np.clip(wet_prob, 0.02, 0.9))[:, None, None]
        amount = rng.gamma(0.8, 4.0, (nd, g.ny, g.nx))
        precip = np.where(occ, amount, 0.0)
        # dewpoint depression and wind
        dd = np.clip(6.0 + 3.0 * dry[:, None, None] + 0.15 * (tmean - 10) - 0.4 * precip, 0.5, 30)
        wspd = np.clip(4.0 + wind_an[:, [0]][:, :, None] + 0.5 * xnorm * wind_an[:, [1]][:, :, None]
                       + 0.3 * rng.standard_normal((nd, g.ny, g.nx)), 0.3, None)
        wdir = np.cumsum(rng.normal(0, 0.4, nd))[:, None, None] + 0 * xnorm
        # soil moisture bucket
        swvl = np.zeros_like(tmean)
        swvl[0] = 0.25
        for t in range(1, nd):
            swvl[t] = np.clip(swvl[t - 1] + 0.004 * precip[t] - 0.0012 * np.clip(tmean[t], 0, None)
                              / 10, 0.05, 0.45)
        daily = {"tmean": tmean, "tmax": tmean + dtr / 2, "dd": dd, "precip": precip,
                 "wspd": wspd, "swvl": swvl}

        # ---- hourly monthly files
        out_dir = self.cfg.raw(src.path)
        out_dir.mkdir(parents=True, exist_ok=True)
        hours_all = pd.date_range(self.days[0], self.days[-1] + pd.Timedelta(hours=23), freq="h")
        local_offset = g.lons[None, :] / 15.0
        month_starts = pd.date_range(self.days[0].to_period("M").to_timestamp(),
                                     self.days[-1], freq="MS")
        for ms in month_starts:
            me = ms + pd.offsets.MonthBegin(1)
            hrs = hours_all[(hours_all >= ms) & (hours_all < me)]
            if len(hrs) == 0:
                continue
            di = ((hrs.normalize() - self.days[0]) / pd.Timedelta(days=1)).astype(int).to_numpy()
            hod = hrs.hour.to_numpy()
            local = (hod[:, None, None] + local_offset[None]) % 24
            diurnal = np.sin(2 * np.pi * (local - 9) / 24)
            t2m = tmean[di] + dtr[di] / 2 * diurnal
            d2m = tmean[di] - dd[di] - 0.15 * dtr[di] * diurnal
            d2m = np.minimum(d2m, t2m)
            spd = wspd[di] * (1 + 0.25 * diurnal)
            u10 = spd * np.cos(wdir[di])
            v10 = spd * np.sin(wdir[di])
            # precipitation falls in a 4-hour burst starting at a day-specific hour; ERA5-Land
            # stores accumulation since 00 UTC, and the 00 UTC step holds the previous day total.
            # Bursts occupy hours 1..22 so the whole daily amount is accumulated by 23 UTC.
            start_h = 1 + (derive_seed(self.seed, "burst") + di * 7) % 19
            frac = ((hod >= start_h) & (hod < start_h + 4)).astype(float) / 4.0
            hourly_rate = precip[di] * frac[:, None, None]  # mm falling in hour (h-1, h]
            n_d = len(hrs) // 24
            rate = hourly_rate.reshape(n_d, 24, g.ny, g.nx)
            acc = np.cumsum(rate, axis=1)
            day_idx = di.reshape(n_d, 24)[:, 0]
            prev = np.where((day_idx - 1)[:, None, None] >= 0,
                            precip[np.maximum(day_idx - 1, 0)], 0.0)
            acc[:, 0] = prev  # 00 UTC step = total of the previous UTC day
            acc = acc.reshape(len(hrs), g.ny, g.nx)
            ds = xr.Dataset(
                {
                    "t2m": (("valid_time", "latitude", "longitude"), (t2m + 273.15).astype("f4"),
                            {"units": "K"}),
                    "d2m": (("valid_time", "latitude", "longitude"), (d2m + 273.15).astype("f4"),
                            {"units": "K"}),
                    "u10": (("valid_time", "latitude", "longitude"), u10.astype("f4"),
                            {"units": "m s**-1"}),
                    "v10": (("valid_time", "latitude", "longitude"), v10.astype("f4"),
                            {"units": "m s**-1"}),
                    "tp": (("valid_time", "latitude", "longitude"), (acc / 1000.0).astype("f4"),
                           {"units": "m", "GRIB_stepType": "accum"}),
                    "swvl1": (("valid_time", "latitude", "longitude"), swvl[di].astype("f4"),
                              {"units": "m**3 m**-3"}),
                },
                coords={"valid_time": hrs.values, "latitude": g.lats, "longitude": g.lons},
                attrs={**_TAGS, "source": "SYNTHETIC ERA5-Land-like hourly fields"},
            )
            enc = {v: {"zlib": True, "complevel": 4} for v in ds.data_vars}
            ds.to_netcdf(out_dir / f"SYNTHETIC_era5_land_{ms:%Y_%m}.nc", encoding=enc)
        return daily

    # ------------------------------------------------------------------ MODIS VI
    def _phenology(self, doy: np.ndarray, lc: np.ndarray) -> np.ndarray:
        peak = {_CROP: 190, _MOSAIC: 185, _GRASS: 165, _SAVANNA: 170, _SHRUB: 150, _FOREST: 200,
                _WET: 190}
        amp = {_CROP: 0.5, _MOSAIC: 0.4, _GRASS: 0.35, _SAVANNA: 0.4, _SHRUB: 0.18,
               _FOREST: 0.45, _WET: 0.35}
        out = np.full(lc.shape, 0.08)
        for cls, pk in peak.items():
            m = lc == cls
            out[m] = 0.12 + amp[cls] * np.exp(-0.5 * ((doy[m] - pk) / 38.0) ** 2)
        out[lc == _WATER] = -0.05
        return out

    def _modis(self, weather: dict[str, np.ndarray]) -> None:
        src = self.cfg.sources.mod13a2
        g = _grid_for(self.bbox, self.sc.modis_resolution_deg, margin=0.05)
        lons, lats = np.meshgrid(g.lons, g.lats)
        lc_idx = (lons.ravel(), lats.ravel())
        eg = self.era_grid
        w = _bilinear_matrix(eg, lons.ravel(), lats.ravel())
        precip_daily = weather["precip"].reshape(len(self.days), -1)
        for year in range(self.d0.year, self.cfg.study.end.year + 1):
            lc = _sample(self.lc_by_year[year - 1], self.base, *lc_idx).reshape(lons.shape)
            for start_doy in range(1, 366, src.composite_length_days):
                start = dt.date(year, 1, 1) + dt.timedelta(days=start_doy - 1)
                if start.year != year:
                    continue
                end = min(start + dt.timedelta(days=src.composite_length_days - 1),
                          dt.date(year, 12, 31))
                mid = start + (end - start) / 2
                rng = self._rng("modis", year, start_doy)
                # drought stress: low 30-day precipitation before composite end lowers NDVI
                i_end = (pd.Timestamp(end) - self.days[0]).days
                i0 = max(i_end - 30, 0)
                if i_end <= 0:
                    p30 = np.full(lons.size, 30.0)
                else:
                    p30 = precip_daily[i0:i_end + 1].sum(axis=0) @ w.T
                stress = np.clip((25 - p30) / 50, 0, 0.3).reshape(lons.shape)
                ndvi = self._phenology(np.full(lc.shape, mid.timetuple().tm_yday), lc)
                ndvi = ndvi * (1 - stress) + rng.normal(0, 0.02, lc.shape)
                evi = 0.62 * ndvi + rng.normal(0, 0.015, lc.shape)
                qa = np.zeros(lc.shape, dtype=np.int16)
                cloud = _smooth(rng, lc.shape, sigma=6) > 1.3
                qa[cloud] = 3
                if mid.month in (12, 1, 2):
                    qa[_smooth(rng, lc.shape, sigma=10) > -0.3] = 2
                qa[(_smooth(rng, lc.shape, sigma=3) > 1.8) & (qa == 0)] = 1
                ndvi_i = np.round(np.clip(ndvi, -0.2, 1) / src.scale_factor).astype(np.int16)
                evi_i = np.round(np.clip(evi, -0.2, 1) / src.scale_factor).astype(np.int16)
                fill = qa == 3
                ndvi_i[fill & (rng.random(lc.shape) < 0.5)] = src.fill_value
                evi_i[ndvi_i == src.fill_value] = src.fill_value
                write_geotiff(
                    self.cfg.raw(src.path) / f"MOD13A2_061_{year}{start_doy:03d}.tif",
                    np.stack([ndvi_i, evi_i, qa]), g.transform, "EPSG:4326",
                    tags={**_TAGS, "composite_start": start.isoformat(),
                          "composite_end": end.isoformat(), "scale_factor": str(src.scale_factor)},
                    band_descriptions=["NDVI", "EVI", "SummaryQA"])

    # ------------------------------------------------------------------ fires
    def _fires(self, weather: dict[str, np.ndarray]) -> None:
        src = self.cfg.sources.firms
        rng = self._rng("fires")
        fg = _grid_for(self.bbox, 0.05, margin=0.0)
        flon, flat = np.meshgrid(fg.lons, fg.lats)
        flon, flat = flon.ravel(), flat.ravel()
        nf = flon.size
        w = _bilinear_matrix(self.era_grid, flon, flat)
        nd = len(self.days)

        def interp(name: str) -> np.ndarray:
            return np.asarray(weather[name].reshape(nd, -1) @ w.T, dtype=np.float32)

        tmax, tmean, dd, prec, wspd = (interp(k) for k in ("tmax", "tmean", "dd", "precip",
                                                            "wspd"))
        rh = 100 * np.exp(17.625 * (tmean - dd) / (243.04 + tmean - dd)) / np.exp(
            17.625 * tmean / (243.04 + tmean))
        cprec = np.cumsum(prec, axis=0)
        p14 = cprec - np.vstack([np.zeros((14, nf)), cprec[:-14]])
        pop = _sample(self.pop_density, self.base, flon, flat)
        # distance to (full) road network, km (approximate, lon scaled by cos(lat))
        from shapely import STRtree

        tree = STRtree(self.all_roads)
        pts = [Point(x, y) for x, y in zip(flon, flat, strict=True)]
        idx, dist = tree.query_nearest(pts, return_distance=True, all_matches=False)
        nearest = np.full(len(pts), np.nan)
        nearest[idx[0]] = dist
        droad = np.asarray(nearest) * 111.0 * 0.75
        months = self.days.month.to_numpy()
        doy = self.days.dayofyear.to_numpy()

        rows: list[dict[str, object]] = []
        for d in range(nd):
            year = self.days[d].year
            lc = _sample(self.lc_by_year.get(year - 1, self.lc_base), self.base, flon, flat)
            m = months[d]
            seas = np.zeros(nf)
            crop = np.isin(lc, [_CROP, _MOSAIC])
            seas[crop] = np.where(m in (4, 5, 9, 10), 2.2, -0.5)
            grass = np.isin(lc, [_GRASS, _SAVANNA, _SHRUB])
            seas[grass] = np.where(m in (7, 8, 9), 1.2, 0.0)
            seas[lc == _FOREST] = np.where(m in (7, 8), 0.6, -0.8)
            seas[np.isin(lc, [_URBAN, _BARREN, _WATER, _WET])] = -4.0
            curing = np.where(grass, 1.0 * np.clip((doy[d] - 170) / 60, 0, 1), 0.0)
            logit = (self.sc.base_ignition_logit + 0.10 * (tmax[d] - 15) - 0.025 * (rh[d] - 50)
                     - 0.06 * np.minimum(p14[d], 40) + 0.12 * wspd[d] + seas + curing
                     + 0.25 * np.log1p(pop) + 0.9 * np.exp(-droad / 5.0)
                     - 3.0 * (tmean[d] < -2))
            p = 1 / (1 + np.exp(-logit))
            ign = np.flatnonzero(rng.random(nf) < p)
            for f in ign:
                rows.extend(self._simulate_fire(rng, self.days[d], flon[f], flat[f],
                                                bool(crop[f])))
        rows.extend(self._industrial(rng))
        df = pd.DataFrame(rows)
        # low-confidence and duplicate rows
        df.loc[rng.random(len(df)) < self.sc.low_confidence_share, "confidence"] = "l"
        dup = df.sample(frac=self.sc.duplicate_share, random_state=int(rng.integers(1 << 31)))
        df = pd.concat([df, dup], ignore_index=True)
        df = df.sort_values(["acq_date", "acq_time"]).reset_index(drop=True)
        out = self.cfg.raw(src.path)
        out.mkdir(parents=True, exist_ok=True)
        df["_y"] = df["acq_date"].str[:4]
        for y, part in df.groupby("_y"):
            part.drop(columns="_y").to_csv(out / f"SYNTHETIC_fire_archive_{y}.csv", index=False)
        log.info("synthetic fires: %d detection rows", len(df))

    def _overpasses(self, day: pd.Timestamp, lon: float, rng: np.random.Generator
                    ) -> list[pd.Timestamp]:
        out = []
        for local in (1.5, 13.5):
            utc_h = (local - lon / 15.0) % 24 + rng.normal(0, 0.4)
            out.append(day + pd.Timedelta(hours=float(utc_h)))
        return sorted(out)

    def _detection_row(self, t: pd.Timestamp, lon: float, lat: float, conf: str, frp: float,
                       ftype: int) -> dict[str, object]:
        local_h = (t.hour + t.minute / 60 + lon / 15) % 24
        return {
            "latitude": round(lat, 5), "longitude": round(lon, 5),
            "bright_ti4": round(320 + 15 * np.log1p(frp), 2), "scan": 0.4, "track": 0.4,
            "acq_date": t.strftime("%Y-%m-%d"), "acq_time": int(t.strftime("%H%M")),
            "satellite": "N", "instrument": "VIIRS", "confidence": conf, "version": "2",
            "bright_ti5": 290.0, "frp": round(frp, 2),
            "daynight": "D" if 6 <= local_h < 18 else "N", "type": ftype,
        }

    def _simulate_fire(self, rng: np.random.Generator, day: pd.Timestamp, lon: float,
                       lat: float, cropland: bool) -> list[dict[str, object]]:
        start = day + pd.Timedelta(hours=float(rng.uniform(0, 24)))
        duration_h = max(3.0, float(rng.exponential(12.0 if cropland else 30.0)))
        end = start + pd.Timedelta(hours=duration_h)
        cx = lon + rng.uniform(-0.025, 0.025)
        cy = lat + rng.uniform(-0.025, 0.025)
        rows = []
        d = day - pd.Timedelta(days=1)
        while d <= end:
            for op in self._overpasses(d, cx, rng):
                if not (start <= op <= end) or rng.random() > 0.75:
                    continue
                age = (op - start) / pd.Timedelta(hours=24)
                n = 1 + rng.poisson(1.5 + 2 * age)
                cx += rng.normal(0, 0.006)
                cy += rng.normal(0, 0.004)
                for _ in range(n):
                    conf = "h" if rng.random() < 0.35 else "n"
                    rows.append(self._detection_row(
                        op, cx + rng.normal(0, 0.005), cy + rng.normal(0, 0.0035), conf,
                        float(rng.lognormal(1.8, 0.8)), 0))
            d += pd.Timedelta(days=1)
        return rows

    def _industrial(self, rng: np.random.Generator) -> list[dict[str, object]]:
        rows = []
        for lon, lat in self.industrial_sites:
            for day in self.days:
                for op in self._overpasses(day, lon, rng):
                    if rng.random() < 0.35:
                        for _ in range(1 + rng.poisson(0.8)):
                            rows.append(self._detection_row(
                                op, lon + rng.normal(0, 0.002), lat + rng.normal(0, 0.0015),
                                "h" if rng.random() < 0.5 else "n",
                                float(rng.lognormal(2.5, 0.5)), 2 if rng.random() < 0.5 else 0))
        return rows


